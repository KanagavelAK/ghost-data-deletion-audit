"""Write code/evaluation/usage_report.md from the LLM usage ledger.

    python code/evaluation/usage_report.py

Reads code/cache/llm_usage.jsonl (one line per model call) and prices it with
the provider's published per-token rates.
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ghost_audit import paths  # noqa: E402
from ghost_audit.dataset import load_requests  # noqa: E402
from ghost_audit.llm import LEDGER_PATH  # noqa: E402

# USD per 1M tokens (input, output), Groq developer-plan list prices as published in October 2026.
PRICES = {
    "qwen/qwen3.8-27b": (0.80, 4.00),
    "openai/gpt-oss-20b": (0.075, 0.30),
    "openai/gpt-oss-120b": (0.15, 0.60),
}
OUT = Path(__file__).resolve().parent / "usage_report.md"


def cost(model: str, tokens_in: int, tokens_out: int) -> float:
    price_in, price_out = PRICES.get(model, (0.0, 0.0))
    return tokens_in / 1e6 * price_in + tokens_out / 1e6 * price_out


def table(rows: list[dict], requests: int) -> list[str]:
    groups = defaultdict(lambda: [0, 0, 0])
    for r in rows:
        g = groups[(r["provider"], r["model"])]
        g[0] += 1
        g[1] += r["input_tokens"]
        g[2] += r["output_tokens"]
    lines = [
        "| Provider | Model | Calls | Input tokens | Output tokens | Total tokens | Avg tokens / request | Est. cost (USD) | Est. cost / request (USD) |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    totals = [0, 0, 0, 0.0]
    for (provider, model), (calls, tin, tout) in sorted(groups.items()):
        c = cost(model, tin, tout)
        lines.append(f"| {provider} | `{model}` | {calls} | {tin:,} | {tout:,} | {tin + tout:,} | {(tin + tout) / requests:,.1f} | {c:.4f} | {c / requests:.6f} |")
        totals = [totals[0] + calls, totals[1] + tin, totals[2] + tout, totals[3] + c]
    calls, tin, tout, c = totals
    lines.append(f"| **All** | | **{calls}** | **{tin:,}** | **{tout:,}** | **{tin + tout:,}** | **{(tin + tout) / requests:,.1f}** | **{c:.4f}** | **{c / requests:.6f}** |")
    return lines


def main() -> int:
    rows = [json.loads(line) for line in LEDGER_PATH.read_text(encoding="utf-8").splitlines() if line.strip()]
    requests = len(load_requests(paths.EVAL_REQUESTS))

    images = [r for r in rows if r["purpose"].startswith("image_extraction")]
    final_images = {}
    for r in images:  # the last extraction of each screenshot is the one in the cache
        final_images[r["purpose"]] = r
    intent = [r for r in rows if r["purpose"].startswith("intent")]

    lines = [
        "# Token Usage and Cost Report",
        "",
        "Generated by `python code/evaluation/usage_report.py` from `code/cache/llm_usage.jsonl`, which records",
        "every model call (provider, model, input and output tokens). Costs use Groq's published developer-plan",
        "prices per 1M tokens: " + ", ".join(f"`{m}` ${i:.3f} in / ${o:.2f} out" for m, (i, o) in PRICES.items() if any(r["model"] == m for r in rows)) + ".",
        "The project ran on Groq's free tier, so the amount actually billed was **$0**; the figures below are",
        "what the same usage would cost on the paid plan.",
        "",
        f"Averages are per evaluation request ({requests} requests in `deletion_requests.csv`).",
        "",
        "## 1. Final full-dataset run (`python code/main.py` → `output.csv`)",
        "",
        "The production run makes **no model calls**: request intent is decided by the rules for all 518",
        "requests (the LLM fallback is only used for texts the rules cannot decide, and there are none), and",
        "screenshot facts are read from the cache. The run is deterministic and takes about 2 seconds.",
        "",
        "| Provider | Model | Calls | Input tokens | Output tokens | Total tokens | Est. cost (USD) |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
        "| — | — | 0 | 0 | 0 | 0 | 0.0000 |",
        "",
        "## 2. One-time preprocessing used by that run: screenshot extraction",
        "",
        f"`output.csv` depends on the cached reading of {len(final_images)} screenshots (`code/cache/image_extractions.json`).",
        "Each call sends the full screenshot plus two zoomed halves (3 images) and the extraction prompt.",
        "",
        "Calls whose results are in the cache (one per screenshot):",
        "",
        *table(list(final_images.values()), requests),
        "",
        f"All extraction calls made during development, including the superseded smoke test and the re-extraction "
        f"of two screenshots ({len(images)} calls):",
        "",
        *table(images, requests),
        "",
        "## 3. Verification only: intent cross-check",
        "",
        "`python code/verify_intent.py` asked the text model to judge all 398 unique request texts in batches of 40",
        "to cross-check the rules (398/398 agreed). It does not affect `output.csv`.",
        "",
        *table(intent, requests),
        "",
        "## 4. Overall (all model calls in the project)",
        "",
        *table(rows, requests),
        "",
        "Wall-clock time of the calls includes waits imposed by the free tier's per-minute token limit; the",
        "client retries on HTTP 429 using the `retry-after` header.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
